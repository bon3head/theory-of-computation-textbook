/**
 * Reusable point class for positioning of player and enemies
 *
 * @class Point
 */
export default class Point {
  /**
   * Creates an instance of Point.
   *
   * @constructor
   * @param {Number} x
   * @param {Number} y
   */
  constructor(x, y) {
    this.x = x;
    this.y = y;
  }
}
